class RulesCog(commands.Cog):
    """Публикация и интерактивное меню правил сервера Litex."""

    def __init__(self, bot: commands.Bot) -> None:
        self.bot = bot

    async def cog_load(self) -> None:
        self.bot.add_view(RulesView())

    @app_commands.command(
        name="rules_setup",
        description="Опубликовать интерактивное сообщение с правилами проекта Litex в текущий канал",
    )
    @app_commands.guild_only()
    @app_commands.default_permissions(administrator=True)
    @app_commands.checks.has_permissions(administrator=True)
    async def rules_setup(self, interaction: discord.Interaction) -> None:
        # Проверка: ТОЛЬКО администратор сервера
        if not isinstance(interaction.user, discord.Member) or not interaction.user.guild_permissions.administrator:
            await interaction.response.send_message(
                "❌ Эту команду могут использовать только администраторы.",
                ephemeral=True,
            )
            return

        if not isinstance(interaction.channel, discord.TextChannel):
            await interaction.response.send_message(
                "❌ Эту команду можно вызвать только в текстовом канале.",
                ephemeral=True,
            )
            return

        await interaction.response.defer(ephemeral=True)

        embeds = []
        main_banner_url = clean_url(MAIN_BANNER)
        if main_banner_url:
            banner_embed = discord.Embed(color=COLOR_PINK)
            banner_embed.set_image(url=main_banner_url)
            embeds.append(banner_embed)

        main_embed = discord.Embed(
            title="🩷 Правила проекта Litex",
            description=(
                "**Добро пожаловать на сервер.**\n"
                "Мы строим сообщество вокруг уважения, порядка и честной игры.\n\n"
                "• **Если возникает конфликт,** сначала сохраняем спокойствие, "
                "затем проверяем правила, а после — обращаемся к администрации.\n"
                "• **Все спорные вопросы решаются** по принципу справедливости и доказательств.\n"
                "• **Незнание правил не освобождает от ответственности!**\n\n"
                "**Как открыть правила**\n"
                "```1) Выбери категорию в меню ниже\n"
                "2) Правила откроются в личном сообщении```\n"
                "**Срок вступления в силу**\n"
                "`Правила действуют с момента первого входа на сервер`"
            ),
            color=COLOR_PINK,
        )
        main_embed.set_footer(text="Проект Litex • Правила")
        embeds.append(main_embed)

        await interaction.channel.send(embeds=embeds, view=RulesView())
        await interaction.followup.send("✅ Панель правил успешно опубликована!", ephemeral=True)


async def setup(bot: commands.Bot) -> None:
    await bot.add_cog(RulesCog(bot))