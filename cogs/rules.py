def clean_url(url: str | None) -> str | None:
    """Очищает ссылку от случайных пробелов, скобок и лишнего '&' на конце."""
    if not url:
        return None
    u = url.strip().strip("<>\"'").rstrip("&")
    return u if u.startswith(("http://", "https://")) else None


